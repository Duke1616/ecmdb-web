/**
 * 判断指定类型是否为网关节点
 */
export const isGatewayType = (type?: string): type is GatewayType => {
  return ["condition", "parallel", "inclusion", "selective"].includes(type as string)
}

/**
 * 获取网关类型配置
 */
export const getGatewayTypeConfig = (type?: string): GatewayTypeConfig | undefined => {
  return GATEWAY_TYPE_LIST.find((item) => item.type === type)
}
